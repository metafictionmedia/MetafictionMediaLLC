#!/usr/bin/env node
// Builds src/lib/morl-payload.ts from the D6-MORL-DEMO.md source.
// The plaintext source is NOT committed (public repo); only the scrambled payload ships.
// Usage: node scripts/build-morl-payload.mjs /path/to/D6-MORL-DEMO.md
//
// Scramble (web-friendly, light — deliberately NOT the app's CryptoKit layers):
//   JSON -> UTF-8 bytes -> XOR with rolling key -> reverse -> base64, then the
//   27 entries are shuffled and their keys are replaced by a salted XOR tag.
import { readFileSync, writeFileSync } from 'node:fs'
import { randomBytes } from 'node:crypto'

const src = process.argv[2]
if (!src) { console.error('usage: build-morl-payload.mjs <D6-MORL-DEMO.md>'); process.exit(1) }
const md = readFileSync(src, 'utf8')

const AXES = {
  m: { A: 'Selfless', B: 'Contractual', C: 'Selfish' },
  a: { X: 'Valiant', Y: 'Functional', Z: 'Anarchic' },
  i: { 1: 'Principled', 2: 'Pragmatic', 3: 'Volatile' },
}

const cards = []
for (const block of md.split(/\n## (?=D6-MORL-)/).slice(1)) {
  const key = block.match(/^(D6-MORL-[ABC][XYZ][123])/)[1]
  const name = (block.match(/\*\*Name:\*\*\s*(.+)/) || [])[1]?.trim()
  const front = block.split(/#### Front\s*\n/)[1]
  if (!front) throw new Error('no Front for ' + key)
  const body = front.split(/\n---\s*(\n|$)/)[0].trim()
  const paragraphs = body.split(/\n\s*\n/).map((p) => p.trim()).filter(Boolean)
  const [m, a, i] = key.slice(-3)
  const expectName = `${AXES.m[m]} · ${AXES.a[a]} · ${AXES.i[i]}`
  if (name !== expectName) throw new Error(`${key}: name "${name}" != "${expectName}"`)
  cards.push({ key, name, paragraphs })
}
if (cards.length !== 27 || new Set(cards.map((c) => c.key)).size !== 27) throw new Error('expected 27 unique cards, got ' + cards.length)

const pad = randomBytes(24)
const salt = randomBytes(4).toString('hex')
const scramble = (str) => {
  const bytes = Buffer.from(str, 'utf8')
  for (let k = 0; k < bytes.length; k++) bytes[k] ^= pad[k % pad.length] ^ (k * 31 & 0xff)
  return Buffer.from(bytes.reverse()).toString('base64')
}
const tag = (key) => scramble(salt + key)

// Fisher–Yates shuffle so entry order leaks nothing.
const shuffled = cards.slice()
for (let k = shuffled.length - 1; k > 0; k--) {
  const j = randomBytes(1)[0] % (k + 1)
  ;[shuffled[k], shuffled[j]] = [shuffled[j], shuffled[k]]
}

const entries = shuffled.map((c) => [tag(c.key), scramble(JSON.stringify({ n: c.name, p: c.paragraphs }))])

const out = `// AUTO-GENERATED by scripts/build-morl-payload.mjs — do not edit by hand.
// Light web scramble of the 27 D6-MORL demo cards (XOR + reverse + base64, shuffled).
// Unscrambled in the browser by src/lib/morl-unscramble.ts.
export const MORL_PAD = ${JSON.stringify(pad.toString('base64'))}
export const MORL_SALT = ${JSON.stringify(salt)}
export const MORL_ENTRIES: ReadonlyArray<readonly [string, string]> = ${JSON.stringify(entries, null, 0).replace(/\],\[/g, '],\n  [')}
`
writeFileSync(new URL('../src/lib/morl-payload.ts', import.meta.url), out)
console.log('wrote', cards.length, 'cards')
